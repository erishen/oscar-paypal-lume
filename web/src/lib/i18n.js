// i18n：en | 中文 切换（对齐原站 EN | 中文 头部开关）
import { ref, computed } from 'vue'

const lang = ref(localStorage.getItem('oscar_lang') || 'zh')

function setLocale(l) {
  lang.value = l
  localStorage.setItem('oscar_lang', l)
  document.documentElement.lang = l === 'zh' ? 'zh' : 'en'
}

// 初始加载同步 <html lang> 与已保存语言（index.html 硬编码 zh；若存了 en 需对齐，读屏发音 + SEO 信号）
setLocale(lang.value)

export function useI18n() {
  return {
    lang,
    isZh: computed(() => lang.value === 'zh'),
    t(key) {
      const m = MESSAGES[lang.value] || MESSAGES.zh
      return m[key] !== undefined ? m[key] : (MESSAGES.en[key] !== undefined ? MESSAGES.en[key] : key)
    },
    switch() {
      setLocale(lang.value === 'zh' ? 'en' : 'zh')
    }
  }
}

